#!/usr/bin/env bun

/**
 * Generates the TypeScript harness protocol bindings consumed by
 * `@slab/api/harness` from the authoritative Rust contract.
 *
 * 1. Runs `cargo test` on the contract crates — the `#[ts(export)]` derives
 *    write per-type `.ts` files into each crate's `bindings/`.
 * 2. Aggregates them into a single
 *    `packages/api/src/harness/generated/index.ts` (types are hoisted in TS,
 *    so a fixed alphabetical concatenation is deterministic and valid).
 * 3. Normalizes ts-rs artifacts to the wire contract: optional fields carry
 *    `| null` from Rust's `Option` even though every one of them
 *    `skip_serializing_if` (never null on the wire), so the null arm is
 *    stripped; `RequestId`'s `i64` arm renders as `bigint` though JSON
 *    numbers decode to JS `number`; and the JSON-RPC envelope frames regain
 *    the `jsonrpc: "2.0"` member the Rust structs deliberately omit (the
 *    transport validates/strips/re-injects it at the wire boundary) while
 *    `params` stays open (`unknown`) for consumers to narrow to the typed
 *    Params layer.
 * 4. Emits the method/notification/error-code constants
 *    (`packages/api/src/harness/constants.ts`) straight from the Rust
 *    `method`/`error_code` const modules (ts-rs generates no constants) and
 *    keeps the Flutter hand-mirror honest with a string-presence check.
 */

import { spawn } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { cargoEnv } from "../cargo/env";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "../..");
const bindingCrates = [
  "crates/slab-exec-policy",
  "crates/slab-jsonrpc",
  "crates/slab-proto",
  "crates/slab-agent",
  "crates/slab-types",
] as const;
const outputPath = path.join(repoRoot, "packages", "api", "src", "harness", "generated", "index.ts");
const constantsPath = path.join(repoRoot, "packages", "api", "src", "harness", "constants.ts");
const generatedHeader = `// @generated by \`bun run gen:harness\` (ts-rs bindings from the Rust
// harness contract in crates/slab-proto + crates/slab-agent +
// crates/slab-jsonrpc + crates/slab-types). Do not edit.

`;
const constantsHeader = `// @generated by \`bun run gen:harness\` (method/notification/error-code
// constants from the Rust harness contract in crates/slab-proto +
// crates/slab-jsonrpc). Do not edit.

`;

function run(command: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: repoRoot,
      stdio: "inherit",
      env: { ...cargoEnv(process.env), ...process.env },
      shell: process.platform === "win32",
    });
    child.on("exit", (code) =>
      code === 0 ? resolve() : reject(new Error(`${command} ${args.join(" ")} exited with ${code}`)),
    );
    child.on("error", reject);
  });
}

async function collectTypeFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  for (const entry of entries) {
    if (entry.isFile() && entry.name.endsWith(".ts")) {
      out.push(path.join(entry.parentPath, entry.name));
    }
  }
  return out;
}

/** Strip ts-rs per-file noise and normalize the wire-optionality. */
function normalizeBody(body: string): string {
  return body
    .split("\n")
    .filter((line) => !line.startsWith("// This file was generated by"))
    .filter((line) => !line.startsWith('import type {'))
    // Optional fields (all `skip_serializing_if` on the Rust side) never carry
    // null on the wire — strip the `| null` ts-rs derives from `Option`.
    .map((line) => line.replace(/((?:"[\w/]+"|\w+)\?: [^,|]+?) \| null([,}])/g, "$1$2"))
    // ts-rs renders empty Rust structs as `Record<symbol, never>`; the wire
    // contract for them is the permissive `{}`.
    .map((line) => line.replace(/= Record<symbol, never>;/g, "= {};"))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const JSONRPC_FRAMES = new Set([
  "JsonRpcRequest",
  "JsonRpcNotification",
  "JsonRpcResponse",
  "JsonRpcErrorResponse",
]);

/**
 * Type-directed normalizations that map the Rust declarations onto the wire
 * truth (run after `normalizeBody`).
 */
function normalizeWireArtifacts(name: string, body: string): string {
  // `RequestId::Integer` is an `i64`, which ts-rs renders as `bigint`; JSON
  // numbers always decode to JS `number` — a `bigint` never survives
  // `JSON.parse`, so the wire type is `string | number`.
  if (name === "RequestId") {
    if (!body.includes("string | bigint")) {
      throw new Error("RequestId binding no longer contains `string | bigint` — update the normalization");
    }
    return body.replace("string | bigint", "string | number");
  }
  if (!JSONRPC_FRAMES.has(name)) return body;
  // Wire truth: the server strips/injects `jsonrpc: "2.0"` at the transport
  // boundary (slab-jsonrpc host.rs parse_wire_message/serialize_wire_message),
  // so the Rust structs omit it — re-add it here, where the frame types are
  // described as they appear on the wire.
  const anchors = body.match(/export type \w+ = \{/g) ?? [];
  if (anchors.length !== 1) {
    throw new Error(`unexpected ${name} shape: ${anchors.length} object literals`);
  }
  const framed = body.replace(/^(export type \w+ = \{ )/m, '$1jsonrpc: "2.0", ');
  // `params` is narrowed by consumers to the typed Params layer; `JsonValue`
  // here would break assigning open `unknown` params at the send site.
  return framed.replace(/\bparams\?: JsonValue,/g, "params?: unknown,");
}

/** The type declaration only (doc comments differ between mirrored crates). */
function canonicalType(body: string): string {
  const withoutComments = body.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
  return withoutComments.replace(/\s+/g, " ").trim();
}

interface RustConst {
  name: string;
  value: string;
  doc: string[];
}

interface MethodConstants {
  requests: RustConst[];
  notifications: RustConst[];
}

/**
 * Parse the `pub mod method` const table from the harness contract. Comments
 * preceding a const travel with it; consts must follow a `// --- Requests` or
 * `// --- Notifications` section marker so a restructured module fails loudly
 * instead of silently dropping constants.
 */
function parseMethodConstants(modSource: string): MethodConstants {
  const block = modSource.match(/pub mod method \{([\s\S]*?)\n\}/)?.[1];
  if (block === undefined) throw new Error("`pub mod method` block not found in mod.rs");

  const requests: RustConst[] = [];
  const notifications: RustConst[] = [];
  let section: "requests" | "notifications" | null = null;
  let comments: string[] = [];
  let buffer = "";
  for (const rawLine of block.split("\n")) {
    const line = rawLine.trim();
    if (line === "") continue;
    if (line.startsWith("// --- Requests")) {
      section = "requests";
      comments = [];
      continue;
    }
    if (line.startsWith("// --- Notifications")) {
      section = "notifications";
      comments = [];
      continue;
    }
    if (line.startsWith("//")) {
      comments.push(line);
      continue;
    }
    buffer += (buffer === "" ? "" : " ") + line;
    if (!line.endsWith(";")) continue;
    const decl = buffer;
    buffer = "";
    const match = decl.match(/^pub const ([A-Z_]+): &str = "(.*)";$/);
    if (match === null) throw new Error(`unrecognized const in \`pub mod method\`: ${decl}`);
    if (section === null) {
      throw new Error(`const ${match[1]} appears before a section marker in \`pub mod method\``);
    }
    (section === "requests" ? requests : notifications).push({
      name: match[1],
      value: match[2],
      doc: comments,
    });
    comments = [];
  }
  if (buffer !== "") throw new Error(`trailing partial declaration in \`pub mod method\`: ${buffer}`);
  if (requests.length === 0 || notifications.length === 0) {
    throw new Error("expected both request and notification consts in `pub mod method`");
  }
  return { requests, notifications };
}

/** Parse `pub const NAME: &str = "value";`-style doc-commented i64 consts. */
function parseI64Consts(source: string, module: string): RustConst[] {
  const block = source.match(new RegExp(`pub mod ${module} \\{([\\s\\S]*?)\\n\\}`))?.[1];
  if (block === undefined) throw new Error(`\`pub mod ${module}\` block not found`);

  const out: RustConst[] = [];
  let comments: string[] = [];
  let buffer = "";
  for (const rawLine of block.split("\n")) {
    const line = rawLine.trim();
    if (line === "") continue;
    if (line.startsWith("///")) {
      comments.push(line);
      continue;
    }
    if (line.startsWith("//")) continue;
    buffer += (buffer === "" ? "" : " ") + line;
    if (!line.endsWith(";")) continue;
    const decl = buffer;
    buffer = "";
    const match = decl.match(/^pub const ([A-Z_]+): i64 = (-?\d+);$/);
    if (match === null) throw new Error(`unrecognized const in \`pub mod ${module}\`: ${decl}`);
    out.push({ name: match[1], value: match[2], doc: comments });
    comments = [];
  }
  if (out.length === 0) throw new Error(`no i64 consts found in \`pub mod ${module}\``);
  return out;
}

function renderDocComments(entry: RustConst): string {
  return entry.doc
    .map((line) =>
      line.startsWith("///")
        ? `  /** ${line.slice(3).trim()} */`
        : `  // ${line.slice(2).trim()}`,
    )
    .join("\n");
}

function renderConstEntries(consts: RustConst[]): string {
  return consts
    .map((entry) => {
      const doc = renderDocComments(entry);
      const decl = `  ${entry.name}: "${entry.value}",`;
      return doc === "" ? decl : `${doc}\n${decl}`;
    })
    .join("\n");
}

function renderConstEntriesRaw(consts: RustConst[]): string {
  return consts
    .map((entry) => {
      const doc = renderDocComments(entry);
      const decl = `  ${entry.name}: ${entry.value},`;
      return doc === "" ? decl : `${doc}\n${decl}`;
    })
    .join("\n");
}

/**
 * Emit `packages/api/src/harness/constants.ts` from the Rust const modules.
 * ts-rs generates no constants, so the single source of truth is parsed
 * straight out of `slab_proto::harness::{method, error_code}` (plus the
 * shared `APPLICATION_ERROR` band reserved in `slab-jsonrpc`).
 */
async function emitMethodConstants(methods: MethodConstants, errorCodes: RustConst[]): Promise<void> {
  const source = `${constantsHeader}// ── Method + error-code constants (mirror \`slab_proto::harness::{method, error_code}\`) ────

/** Client → server requests. */
export const HARNESS_METHOD = {
${renderConstEntries(methods.requests)}
} as const

/** Server → client notifications (agent event delivery). */
export const HARNESS_NOTIFICATION = {
${renderConstEntries(methods.notifications)}
} as const

/** Harness-specific error codes (reserved; the dispatcher currently emits \`-32000\`). */
export const HARNESS_ERROR_CODE = {
${renderConstEntriesRaw(errorCodes)}
} as const
`;
  await mkdir(path.dirname(constantsPath), { recursive: true });
  await writeFile(constantsPath, source, "utf8");
  console.log(
    `Generated ${path.relative(repoRoot, constantsPath).replace(/\\/g, "/")} ` +
      `(${methods.requests.length} methods, ${methods.notifications.length} notifications, ${errorCodes.length} error codes).`,
  );

  // The Flutter client mirrors the same constants by hand (no ts-rs Dart
  // emitter exists); keep the Dart file honest with a string-presence check.
  const dartPath = path.join(
    repoRoot,
    "flutter",
    "slab-mobile",
    "lib",
    "data",
    "harness",
    "harness_methods.dart",
  );
  const dartSource = await readFile(dartPath, "utf8").catch(() => null);
  if (dartSource === null) {
    // A missing file must fail loudly — silently skipping would turn the
    // drift check into a no-op after any future move.
    throw new Error(
      `flutter/slab-mobile/lib/data/harness/harness_methods.dart not found — the harness-constant mirror moved or was deleted; update this script.`,
    );
  }
  const dartDrift = [...methods.requests, ...methods.notifications]
    .map((entry) => entry.value)
    .filter((value) => !dartSource.includes(`'${value}'`));
  if (dartDrift.length > 0) {
    throw new Error(
      `HARNESS_METHOD values missing from flutter/slab-mobile/lib/data/harness/harness_methods.dart:\n${dartDrift.map((v) => `  ${v}`).join("\n")}`,
    );
  }
  console.log(`Method constants emitted (${methods.requests.length + methods.notifications.length} consts, Flutter mirror in sync).`);
}

async function main() {
  await run("cargo", [
    "test",
    ...bindingCrates.flatMap((crate) => ["-p", path.basename(crate)]),
  ]);

  const byName = new Map<string, string>();
  for (const crate of bindingCrates) {
    for (const file of await collectTypeFiles(path.join(repoRoot, crate, "bindings"))) {
      const name = path.basename(file, ".ts").split("/").pop()!;
      const body = normalizeWireArtifacts(name, normalizeBody(await readFile(file, "utf8")));
      const existing = byName.get(name);
      // Cross-crate mirrors (e.g. ApprovalScope) may differ only in doc
      // comments; the wire type itself must be identical.
      if (existing !== undefined && canonicalType(existing) !== canonicalType(body)) {
        throw new Error(`binding ${name} differs between crates — resolve the divergence first`);
      }
      if (existing === undefined) byName.set(name, body);
    }
  }
  if (byName.size === 0) throw new Error("no bindings generated");

  const sections = [...byName.entries()]
    .toSorted(([a], [b]) => a.localeCompare(b))
    .map(([name, body]) => `// ── ${name} ──\n${body}`)
    .join("\n\n");

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generatedHeader + sections + "\n", "utf8");
  console.log(
    `Generated ${path.relative(repoRoot, outputPath).replace(/\\/g, "/")} (${byName.size} types).`,
  );

  const modSource = await readFile(
    path.join(repoRoot, "crates", "slab-proto", "src", "harness", "mod.rs"),
    "utf8",
  );
  const jsonrpcSource = await readFile(
    path.join(repoRoot, "crates", "slab-jsonrpc", "src", "lib.rs"),
    "utf8",
  );
  const applicationErrorCode = jsonrpcSource.match(
    /pub const APPLICATION_ERROR: i64 = (-?\d+);/,
  )?.[1];
  if (applicationErrorCode !== "-32000") {
    throw new Error("APPLICATION_ERROR (-32000) not found in slab-jsonrpc/src/lib.rs");
  }
  const applicationError: RustConst = { name: "APPLICATION_ERROR", value: applicationErrorCode, doc: [] };
  await emitMethodConstants(
    parseMethodConstants(modSource),
    [applicationError, ...parseI64Consts(modSource, "error_code")],
  );
}

await main();
